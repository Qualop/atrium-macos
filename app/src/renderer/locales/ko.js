// Preserve the macOS fork's existing copy, while adding every new upstream key.
import core from './ko-core.js';
import sessions from './ko-sessions.js';
import workspace from './ko-workspace.js';
import controls from './ko-controls.js';
function mergeCopy(base, local) {
  const result = { ...base };
  for (const [key, value] of Object.entries(local)) {
    result[key] = value && typeof value === 'object' && !Array.isArray(value)
      ? mergeCopy(typeof base?.[key] === 'object' ? base[key] : {}, value) : value;
  }
  return result;
}
const dictionary = mergeCopy(upstream, { ...core, ...sessions, ...workspace, ...controls,
  thread: { ...sessions.thread, title: '요청 기록' },
});
// P45 removed the automatic entry briefing, including its unused labels.
delete dictionary.node.briefTitle;
for (const key of ['briefTitle', 'touched', 'stateNow', 'pendingQuestion', 'lastPrompt', 'lastAnswer', 'interruptedBy', 'briefNote']) delete dictionary.extras[key];
dictionary.backend.launchers = { err: { notFound: dictionary.launchers.err.notFound } };
export default dictionary;
